/*
 * Writes lib/src/icons.g.dart: one constant per icon on DevignerIcons,
 * holding the inner markup of its five drawings, rendered from the built React
 * components. devigner_icon.dart (hand-written) draws them.
 *
 * Static constants on one class, like Flutter's own Icons: a release build
 * tree-shakes the ones an app never reads.
 *
 *   node scripts/build.mjs
 */
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { allSvgs, splitSvg, STYLES } from "../../icons/scripts/emit-svg.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
/* The version of @devigner-ui/icons, so this ships beside it as the same release. */
const { version } = JSON.parse(readFileSync(path.join(ROOT, "..", "icons", "package.json"), "utf8"));

/* DevignerIconData.svg writes the root itself with these. */
const ROOT_ATTRS = JSON.stringify({
  width: "24", height: "24", viewBox: "0 0 24 24", fill: "none", xmlns: "http://www.w3.org/2000/svg",
});

/* Lowercased, these collide with Dart's reserved words. */
const RESERVED = new Set(
  ("assert break case catch class const continue default do else enum extends false final finally " +
    "for if in is new null rethrow return super switch this throw true try var void while with").split(" "),
);

/** BagStraps -> bagStraps; 3dCube -> $3dCube; Switch -> switch$. */
export function dartName(name) {
  const lower = name[0].toLowerCase() + name.slice(1);
  if (/^\d/.test(lower)) return `$${lower}`;
  return RESERVED.has(lower) ? `${lower}$` : lower;
}

const icons = await allSvgs();
const lines = [];
for (const [name, drawings] of icons) {
  const inner = STYLES.map((style) => {
    const { attrs, inner } = splitSvg(drawings[style]);
    assert.equal(JSON.stringify(attrs), ROOT_ATTRS, `${name} ${style} has its own root attributes`);
    assert.ok(!inner.includes("'"), `${name} ${style} has a single quote, which a raw string cannot hold`);
    return `r'${inner}'`;
  });
  lines.push(`  static const ${dartName(name)} = DevignerIconData('${name}', ${inner.join(", ")});`);
}

writeFileSync(
  path.join(ROOT, "lib", "src", "icons.g.dart"),
  `// GENERATED CODE - DO NOT EDIT\n// Generated by scripts/build.mjs from @devigner-ui/icons\n` +
    `// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars\n\n` +
    `import 'devigner_icon.dart';\n\n` +
    `/// Every Devigner icon, for [DevignerIcon].\nabstract final class DevignerIcons {\n${lines.join("\n")}\n}\n`,
);

/* The pub version is @devigner-ui/icons's, set above. */
const pubspec = path.join(ROOT, "pubspec.yaml");
writeFileSync(pubspec, readFileSync(pubspec, "utf8").replace(/^version: .*$/m, `version: ${version}`));

console.log(`ok  ${icons.size} icons for Flutter`);
