/*
 * Writes DvIcons.g.cs: one static property per icon, holding the inner
 * markup of its five drawings, rendered from the built React components.
 * DvIcon.cs (hand-written) draws them.
 *
 * Properties, not fields: an unused property is a method the trimmer can drop,
 * where a static field would be initialised, and kept, with the class.
 *
 *   node scripts/build.mjs
 */
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { allSvgs, splitSvg, STYLES } from "../../icons/scripts/emit-svg.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const PROJECT = path.join(ROOT, "src", "Devigner.Icons.Blazor");
/* The version of @devigner-ui/icons, so this ships beside it as the same release. */
const { version } = JSON.parse(readFileSync(path.join(ROOT, "..", "icons", "package.json"), "utf8"));

/* DvIcon writes the <svg> itself with these, so every drawing has to agree. */
const ROOT_ATTRS = JSON.stringify({
  width: "24", height: "24", viewBox: "0 0 24 24", fill: "none", xmlns: "http://www.w3.org/2000/svg",
});

const icons = await allSvgs();
const verbatim = (s) => `@"${s.replace(/"/g, '""')}"`;
const lines = [];
for (const [name, drawings] of icons) {
  const inner = STYLES.map((style) => {
    const { attrs, inner } = splitSvg(drawings[style]);
    assert.equal(JSON.stringify(attrs), ROOT_ATTRS, `${name} ${style} has its own root attributes`);
    return verbatim(inner);
  });
  /* C# names cannot start with a digit: 3dCube is _3dCube. */
  const id = /^\d/.test(name) ? `_${name}` : name;
  lines.push(`    /// <summary>The ${name} icon.</summary>\n    public static IconData ${id} => new(${JSON.stringify(name)}, ${inner.join(", ")});`);
}

writeFileSync(
  path.join(PROJECT, "DvIcons.g.cs"),
  `// <auto-generated />\n// Generated by scripts/build.mjs from @devigner-ui/icons\n\n` +
    `namespace Devigner.Icons.Blazor;\n\n` +
    `/// <summary>Every Devigner icon, for <see cref="DvIcon"/>.</summary>\n` +
    `public static class DvIcons\n{\n${lines.join("\n")}\n}\n`,
);

/* The package version is @devigner-ui/icons's, set above. */
const csproj = path.join(PROJECT, "Devigner.Icons.Blazor.csproj");
writeFileSync(
  csproj,
  readFileSync(csproj, "utf8").replace(/<Version>[^<]*<\/Version>/, `<Version>${version}</Version>`),
);

console.log(`ok  ${icons.size} icons for Blazor`);
