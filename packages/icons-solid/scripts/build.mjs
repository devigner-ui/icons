/*
 * Writes the SolidJS package: one module per icon, a barrel, and the types.
 *
 * The drawings come from ../../icons/scripts/emit-svg.mjs, which renders the
 * built React components, so the artwork has one source and it is not here.
 * No aliases for old names: this package starts at 3.5.0, after the renames.
 *
 *   node scripts/build.mjs
 */
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { allSvgs, splitSvg, STYLES } from "../../icons/scripts/emit-svg.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const DIST = path.join(ROOT, "dist");

const icons = await allSvgs();

rmSync(DIST, { recursive: true, force: true });
mkdirSync(path.join(DIST, "icons"), { recursive: true });
copyFileSync(path.join(ROOT, "src", "runtime.js"), path.join(DIST, "runtime.js"));

const names = [];
for (const [name, drawings] of icons) {
  const split = Object.fromEntries(
    Object.keys(drawings).map((style) => [style, splitSvg(drawings[style])]),
  );
  writeFileSync(
    path.join(DIST, "icons", `${name}.js`),
    `// AUTO-GENERATED - DO NOT EDIT\n` +
      `// Generated by scripts/build.mjs from @devigner-ui/icons\n` +
      `import { icon } from "../runtime.js";\n\n` +
      `export default /* #__PURE__ */ icon(${JSON.stringify(split)});\n`,
  );
  names.push(name);
}

writeFileSync(
  path.join(DIST, "index.js"),
  `// AUTO-GENERATED - DO NOT EDIT\n` +
    `// Generated by scripts/build.mjs\n\n` +
    names.map((n) => `export { default as Icon${n} } from "./icons/${n}.js";`).join("\n") +
    "\n",
);

writeFileSync(
  path.join(DIST, "index.d.ts"),
  `// AUTO-GENERATED - DO NOT EDIT\n` +
    `// Generated by scripts/build.mjs\n\n` +
    `import type { Component, JSX } from "solid-js";\n\n` +
    `export type IconStyle = ${STYLES.map((s) => `"${s}"`).join(" | ")};\n\n` +
    `export type IconName = ${names.map((n) => `"${n}"`).join(" | ")};\n\n` +
    `export interface IconProps extends JSX.SvgSVGAttributes<SVGSVGElement> {\n` +
    `  /** Which drawing to render. Defaults to "outline". */\n` +
    `  variant?: IconStyle;\n` +
    `  /** Line weight of outline, twotone and broken, in the drawing's units. */\n` +
    `  strokeWidth?: string | number;\n` +
    `}\n\n` +
    `export type IconComponent = Component<IconProps>;\n\n` +
    names.map((n) => `export declare const Icon${n}: IconComponent;`).join("\n") +
    "\n",
);

console.log(`ok  ${names.length} Solid components, a barrel and types`);
