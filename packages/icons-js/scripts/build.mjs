/*
 * Writes the plain JS package: one data module per icon, the runtime that
 * turns them into markup, a barrel and the types.
 *
 * The drawings come from ../../icons/scripts/emit-svg.mjs, which renders the
 * built React components, so the artwork has one source and it is not here.
 * No aliases for old names: this package starts at 3.5.0, after the renames,
 * so nobody has an old name to keep working.
 *
 *   node scripts/build.mjs
 */
import { copyFileSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { allSvgs, splitSvg, STYLES } from "../../icons/scripts/emit-svg.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const DIST = path.join(ROOT, "dist");

const icons = await allSvgs();

rmSync(DIST, { recursive: true, force: true });
mkdirSync(path.join(DIST, "icons"), { recursive: true });
copyFileSync(path.join(ROOT, "src", "runtime.js"), path.join(DIST, "runtime.js"));

const names = [];
for (const [name, drawings] of icons) {
  const split = Object.fromEntries(
    Object.keys(drawings).map((style) => [style, splitSvg(drawings[style])]),
  );
  writeFileSync(
    path.join(DIST, "icons", `${name}.js`),
    `// AUTO-GENERATED - DO NOT EDIT\n` +
      `// Generated by scripts/build.mjs from @devigner-ui/icons\n` +
      `export default ${JSON.stringify(split)};\n`,
  );
  writeFileSync(
    path.join(DIST, "icons", `${name}.d.ts`),
    `import type { IconData } from "../index.js";\ndeclare const icon: IconData;\nexport default icon;\n`,
  );
  names.push(name);
}

writeFileSync(
  path.join(DIST, "index.js"),
  `// AUTO-GENERATED - DO NOT EDIT\n` +
    `// Generated by scripts/build.mjs\n\n` +
    `export { toSvg, toElement, createIcons } from "./runtime.js";\n` +
    names.map((n) => `export { default as Icon${n} } from "./icons/${n}.js";`).join("\n") +
    "\n",
);

writeFileSync(
  path.join(DIST, "index.d.ts"),
  `// AUTO-GENERATED - DO NOT EDIT\n` +
    `// Generated by scripts/build.mjs\n\n` +
    `export type IconStyle = ${STYLES.map((s) => `"${s}"`).join(" | ")};\n\n` +
    `export type IconName = ${names.map((n) => `"${n}"`).join(" | ")};\n\n` +
    `/** One icon: each style's root attributes and inner markup. */\n` +
    `export type IconData = Record<IconStyle, { attrs: Record<string, string>; inner: string }>;\n\n` +
    `export interface IconOptions {\n` +
    `  /** Which drawing to render. Defaults to "outline". */\n` +
    `  variant?: IconStyle;\n` +
    `  /** Line weight of outline, twotone and broken, in the drawing's units. */\n` +
    `  strokeWidth?: string | number;\n` +
    `  /** Attributes for the <svg>: class, id, aria-label and so on. */\n` +
    `  attrs?: Record<string, string | number | boolean | null | undefined>;\n` +
    `}\n\n` +
    `export declare function toSvg(icon: IconData, options?: IconOptions): string;\n` +
    `export declare function toElement(icon: IconData, options?: IconOptions): SVGSVGElement;\n` +
    `export declare function createIcons(options: {\n` +
    `  icons: Record<string, IconData>;\n` +
    `  root?: ParentNode;\n` +
    `  attribute?: string;\n` +
    `}): number;\n\n` +
    names.map((n) => `export declare const Icon${n}: IconData;`).join("\n") +
    "\n",
);

console.log(`ok  ${names.length} icons as data, toSvg, toElement and createIcons`);
