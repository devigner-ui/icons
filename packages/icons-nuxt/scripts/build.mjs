/*
 * Writes the Nuxt module: the module itself, copied, and the list of icon
 * names it registers, read from the built Vue package's types so the two
 * cannot disagree. No old names: this package starts at 3.5.0.
 *
 *   node scripts/build.mjs        (after building @devigner-ui/icons-vue)
 */
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const DIST = path.join(ROOT, "dist");

const vue = path.dirname(createRequire(import.meta.url).resolve("@devigner-ui/icons-vue/package.json"));
const types = readFileSync(path.join(vue, "dist", "index.d.ts"), "utf8");
const union = types.match(/export type IconName = ([^;]+);/)?.[1];
if (!union) throw new Error("@devigner-ui/icons-vue has no IconName type. Build it first.");
const names = [...union.matchAll(/"(\w+)"/g)].map((m) => m[1]);

rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });
copyFileSync(path.join(ROOT, "src", "module.mjs"), path.join(DIST, "module.mjs"));
writeFileSync(
  path.join(DIST, "names.mjs"),
  `// AUTO-GENERATED - DO NOT EDIT\n// Generated by scripts/build.mjs from @devigner-ui/icons-vue\n` +
    `export const names = ${JSON.stringify(names)};\n`,
);
writeFileSync(
  path.join(DIST, "module.d.mts"),
  `import type { NuxtModule } from "@nuxt/schema";\n\n` +
    `export interface ModuleOptions {\n` +
    `  /** Put before every icon name. "Icon" gives <IconBagStraps>. */\n` +
    `  prefix?: string;\n` +
    `}\n\n` +
    `declare const module: NuxtModule<ModuleOptions>;\nexport default module;\n`,
);

console.log(`ok  a Nuxt module registering ${names.length} icons`);
