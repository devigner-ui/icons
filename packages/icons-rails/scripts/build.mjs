/*
 * Writes the gem's drawings: lib/devigner_icons/svg/<style>/<Name>.svg, the
 * same files @devigner-ui/icons-svg ships, rendered from the built React
 * components. The Ruby around them is hand-written; this only fills the
 * folder it reads, and the gem version, so it moves with the other packages.
 *
 *   node scripts/build.mjs
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { allSvgs } from "../../icons/scripts/emit-svg.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const SVG = path.join(ROOT, "lib", "devigner_icons", "svg");
/* The version of @devigner-ui/icons, so this ships beside it as the same release. */
const { version } = JSON.parse(readFileSync(path.join(ROOT, "..", "icons", "package.json"), "utf8"));

const icons = await allSvgs();
rmSync(SVG, { recursive: true, force: true });
for (const [name, drawings] of icons) {
  for (const [style, svg] of Object.entries(drawings)) {
    mkdirSync(path.join(SVG, style), { recursive: true });
    writeFileSync(path.join(SVG, style, `${name}.svg`), svg);
  }
}
writeFileSync(
  path.join(ROOT, "lib", "devigner_icons", "version.rb"),
  `# frozen_string_literal: true\n\n# Generated by scripts/build.mjs: the version of @devigner-ui/icons.\nmodule DevignerIcons\n  VERSION = "${version}"\nend\n`,
);

console.log(`ok  ${icons.size} icons as SVG files for the gem`);
